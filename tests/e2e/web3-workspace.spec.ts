import { expect, test } from "@playwright/test";
// Browser plugin not available. Real Dockview + Sales editors, explicit Lab Receipt lifetime stub.
test.beforeEach(async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 });
  page.on("dialog", dialog => void dialog.accept());
  await page.goto("/lab/sales");
});
test("same record IDs have independent buffers and commands through split, native close and read-only tabs", async ({ page }, info) => {
  const errors: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.getByRole("button", { name: "Mở mẫu 1001", exact: true }).click();
  const sale = page.getByRole("region", { name: "Chứng từ 1001", exact: true });
  await sale.getByLabel("Ghi chú", { exact: true }).fill("Sales riêng");
  const saleId = await sale.getAttribute("data-session-id");
  await page.getByRole("button", { name: "Mở Receipt stub 1001", exact: true }).click();
  const receipt = page.getByRole("region", { name: "Nhập kho stub 1001", exact: true });
  await expect(receipt).not.toHaveAttribute("data-session-id", saleId!);
  await receipt.getByLabel("Raw Receipt").pressSequentially("Receipt raw");
  await page.getByRole("button", { name: "Tách sang phải", exact: true }).click();
  await expect(sale.getByLabel("Ghi chú", { exact: true })).toHaveValue("Sales riêng");
  await expect(receipt.getByLabel("Raw Receipt")).toHaveValue("Receipt raw");
  await receipt.getByLabel("Raw Receipt").press("Control+Alt+m");
  await expect(receipt).toContainText("Lệnh: 1");
  await page.getByRole("tab", { name: "Nhập kho 1001", exact: true }).press("Delete");
  await expect(page.getByRole("dialog")).toContainText("Đóng Nhập kho 1001?");
  await page.getByRole("button", { name: "Tiếp tục sửa", exact: true }).click();
  await expect(receipt.getByLabel("Raw Receipt")).toHaveValue("Receipt raw");
  await page.getByRole("button", { name: "Thẻ kho stub", exact: true }).click();
  await expect(page.getByRole("button", { name: "Đánh dấu phiên", exact: true })).toBeDisabled();
  await expect(page.getByRole("button", { name: "Sales mới", exact: true })).toBeDisabled();
  await page.keyboard.press("Control+Alt+m");
  await page.getByRole("tab", { name: "Thẻ kho", exact: true }).press("Backspace");
  await expect(page.getByRole("tab", { name: "Thẻ kho", exact: true })).toHaveCount(0);
  await page.getByRole("tab", { name: "Nhập kho 1001", exact: true }).click();
  await expect(receipt).toContainText("Lệnh: 1");
  await page.screenshot({ path: info.outputPath("two-module-workspace.png") });
  expect(errors).toEqual([]);
});
test("unknown Receipt blocks close-all and reset after earlier admitted Sales closes", async ({ page }) => {
  await page.getByRole("button", { name: "Mở mẫu 1001", exact: true }).click();
  await page.getByRole("button", { name: "Mở Receipt stub 1001", exact: true }).click();
  const receipt = page.getByRole("region", { name: "Nhập kho stub 1001", exact: true });
  await receipt.getByLabel("Raw Receipt").fill("-");
  await receipt.getByRole("button", { name: "Stub unknown", exact: true }).click();
  await page.getByRole("button", { name: "Đóng tất cả", exact: true }).click();
  await expect(page.getByRole("tab", { name: "Sales 1001", exact: true })).toHaveCount(0);
  await expect(receipt).toContainText("outcome-unknown");
  await page.getByRole("button", { name: "Đặt lại bố cục", exact: true }).click();
  await expect(receipt.getByLabel("Raw Receipt")).toHaveValue("-");
  await receipt.getByRole("button", { name: "Stub đối soát", exact: true }).click();
  await page.getByRole("button", { name: "Đóng tài liệu", exact: true }).click();
  await page.getByRole("dialog").getByRole("button", { name: "Lưu", exact: true }).click();
  await expect(receipt.getByLabel("Raw Receipt")).toHaveValue("-");
  await page.getByRole("button", { name: "Đóng tài liệu", exact: true }).click();
  await page.getByRole("button", { name: "Bỏ thay đổi", exact: true }).click();
  await expect(receipt).toHaveCount(0);
});
test("route remount preserves both stores and multiple unsaved Receipt identities", async ({ page }) => {
  await page.getByRole("button", { name: "Mở mẫu 1001", exact: true }).click();
  await page.getByRole("button", { name: "Mở Receipt stub 1001", exact: true }).click();
  const receipt = page.getByRole("region", { name: "Nhập kho stub 1001", exact: true });
  await receipt.getByLabel("Raw Receipt").fill("raw retained");
  const id = await receipt.getAttribute("data-session-id");
  await page.getByRole("button", { name: "Nhập kho mới", exact: true }).click();
  await page.getByRole("button", { name: "Nhập kho mới", exact: true }).click();
  await expect(page.getByRole("tab", { name: "Nhập kho mới", exact: true })).toHaveCount(2);
  await page.getByRole("link", { name: "Components Lab", exact: true }).click();
  await page.getByRole("tab", { name: "Nhập kho 1001", exact: true }).click();
  await expect(receipt).toHaveAttribute("data-session-id", id!);
  await expect(receipt.getByLabel("Raw Receipt")).toHaveValue("raw retained");
});
